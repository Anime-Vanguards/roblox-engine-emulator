#!/usr/bin/env node
// The properties whose Read or Write permit names capabilities a script may lack: data/capability-properties.rs, written from
// data/reflection-security.json (and data/reflection.json, for the Read permit of a property a game script's view lists):
//
//   node tools/capability-properties.mjs          write the table
//   node tools/capability-properties.mjs --check  the committed table is exactly what the two files make (fails otherwise)
//
// An entry is (the class that declares the property, its name, its Read permit's capabilities, its Write permit's, whether
// IsPropertyModified, ResetPropertyToDefault and GetStyled take it for a property: all but a BinaryString), a permit a property lacks
// being None and one that needs nothing "". It lists:
// - the properties with a permit that needs a capability a game script lacks (src/services/reflection_data.rs SCRIPT_CAPS: Plugin,
//   LocalUser, RobloxScript, RobloxEngine, PluginOrOpenCloud, ...; every other script holds those a game script holds): those a game
//   script's view hides, and those it lists whose Write permit it hides (Lighting.LightingStyle: Write needs PluginOrOpenCloud);
// - the hidden properties with no permit at all, which are no member (a client answers "is not a valid member", as for a name no
//   class has) but which GetPropertyChangedSignal calls "not a scriptable property".
// src/reflection.rs reads it (Reflection::restriction); what a client does with each is in docs/engine.md "Capabilities".
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "data", "capability-properties.rs");
const security = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "reflection-security.json"), "utf8"));
const dump = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "reflection.json"), "utf8"));
// (the capabilities a game script lacks: every one outside RunClientScript..AvatarBehavior in src/lua/prelude.luau CapabilityOrder)
const ORDER = fs.readFileSync(path.join(ROOT, "src", "lua", "prelude.luau"), "utf8").match(/local CapabilityOrder = {([^}]*)}/)[1].match(/"([A-Za-z]+)"/g).map((name) => name.slice(1, -1));
const held = new Set(ORDER.slice(ORDER.indexOf("RunClientScript"), ORDER.indexOf("AvatarBehavior") + 1));
const ALIASES = { AssetRequire: "LoadUnownedAsset", Avatar: "AvatarAppearance" };
const refusable = (permit) => permit !== undefined && permit.split("|").map((name) => name.trim()).filter(Boolean).some((name) => !held.has(ALIASES[name] ?? name));
const listed = new Map(dump.classes.map((c) => [c.name, new Map(c.properties.map((p) => [p.name, p]))]));

const entries = [];
for (const c of [...security.classes, ...security.extend]) {
	for (const p of c.properties || []) {
		const { Read: read, Write: write } = p.permits;
		if (refusable(read) || refusable(write) || (read === undefined && write === undefined)) entries.push([c.name, p.name, read, write, p.type.engine !== "BinaryString"]);
	}
	for (const [name, permits] of Object.entries(c.permits?.properties || {})) {
		if (permits.Write === undefined) continue;
		const own = listed.get(c.name)?.get(name);
		if (!own) throw new Error(`${c.name}.${name}: a hidden Write permit of a property data/reflection.json does not list`);
		const read = own.permits?.Read ?? permits.Read;
		if (refusable(read) || refusable(permits.Write)) entries.push([c.name, name, read, permits.Write, own.type?.engine !== "BinaryString"]);
	}
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0));
const text = (value) => (value === undefined ? "None" : `Some(${JSON.stringify(value)})`);
const out = [
	"// Generated by tools/capability-properties.mjs from data/reflection-security.json and data/reflection.json",
	`// (${security.version}). Do not edit; run the tool.`,
	"//",
	"// (the declaring class, the property, its Read permit's capabilities, its Write permit's (None: no such permit), whether the",
	"// property-name methods take it: all but a BinaryString)",
	"&[",
	...entries.map(([c, p, r, w, typed]) => `    (${JSON.stringify(c)}, ${JSON.stringify(p)}, ${text(r)}, ${text(w)}, ${typed}),`),
	"]",
	"",
].join("\n");

if (process.argv.includes("--check")) {
	const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
	if (committed !== out) {
		console.error("capability-properties: data/capability-properties.rs is not what data/reflection-security.json makes: run node tools/capability-properties.mjs");
		process.exit(1);
	}
	console.log(`capability-properties: ${entries.length} entries, up to date`);
} else {
	fs.writeFileSync(OUT, out);
	console.log(`capability-properties: wrote ${entries.length} entries`);
}
